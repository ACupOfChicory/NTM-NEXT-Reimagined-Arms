#!/usr/bin/env python3
# Builds res/ntmgunfeel-bullet-masks.properties: which pixels of a see-through block (bars, chain-link fence,
# grates) stop a bullet. The server has no textures, so the alpha of each block's texture is read here, once.
# Line: <block id>.<face axis x|y|z or *> = 64 hex digits, 16 rows of 16 pixels from the top, 1 = solid.
# Usage: tools/bullet_masks.py <minecraft client jar> <NTM jar> [preview.png]
import sys, zlib, struct, zipfile

def decode(data):
    i = 8; idat = b''; pal = b''; trns = b''
    while i < len(data):
        l = struct.unpack('>I', data[i:i+4])[0]; t = data[i+4:i+8]; d = data[i+8:i+8+l]
        if t == b'IHDR': W, H, bd, ct = struct.unpack('>IIBB', d[:10])
        elif t == b'PLTE': pal = d
        elif t == b'tRNS': trns = d
        elif t == b'IDAT': idat += d
        i += 12 + l
    assert bd == 8, 'only 8-bit PNGs'
    bpp = {6: 4, 2: 3, 3: 1, 4: 2, 0: 1}[ct]
    raw = zlib.decompress(idat); stride = W * bpp; rows = []; prev = bytearray(stride)
    for y in range(H):
        f = raw[y*(stride+1)]; line = bytearray(raw[y*(stride+1)+1:(y+1)*(stride+1)])
        for x in range(stride):
            a = line[x-bpp] if x >= bpp else 0; b = prev[x]; c = prev[x-bpp] if x >= bpp else 0
            if f == 1: line[x] = (line[x] + a) & 255
            elif f == 2: line[x] = (line[x] + b) & 255
            elif f == 3: line[x] = (line[x] + (a + b) // 2) & 255
            elif f == 4:
                p = a + b - c; pa, pb, pc = abs(p-a), abs(p-b), abs(p-c)
                line[x] = (line[x] + (a if pa <= pb and pa <= pc else b if pb <= pc else c)) & 255
        rows.append(bytes(line)); prev = line
    def alpha(x, y):
        r = rows[y]
        if ct == 6: return r[x*4+3]
        if ct == 4: return r[x*2+1]
        if ct == 3: k = r[x]; return trns[k] if k < len(trns) else 255
        return 255
    return W, H, alpha

def mask(data):
    W, H, alpha = decode(data)
    n = W  # an animated texture is a strip of square frames: use the first
    bits = []
    for y in range(16):
        for x in range(16):
            bits.append(1 if alpha(x * n // 16, y * n // 16) >= 128 else 0)
    return ''.join('%x' % int(''.join(map(str, bits[i:i+4])), 2) for i in range(0, 256, 4)), bits

mc = zipfile.ZipFile(sys.argv[1]); ntm = zipfile.ZipFile(sys.argv[2])
def tex(jar, path): return jar.read(path)
V = lambda n: tex(mc, 'assets/minecraft/textures/block/%s.png' % n)
N = lambda n: tex(ntm, 'assets/hbm/textures/block/%s.png' % n)
# block -> {face axis or '*': texture}
blocks = {
    'minecraft:iron_bars': {'*': V('iron_bars')},
    'hbm:fence_metal': {'*': N('fence_metal')},
    'hbm:steel_grate': {'y': N('grate_top'), '*': N('grate_side')},
    'hbm:steel_grate_wide': {'y': N('grate_wide_top'), '*': N('grate_side')},
}
for c in ['', 'exposed_', 'weathered_', 'oxidized_']:
    for w in ['', 'waxed_']:
        blocks['minecraft:%s%scopper_bars' % (w, c)] = {'*': V('%scopper_bars' % c)}
        blocks['minecraft:%s%scopper_grate' % (w, c)] = {'*': V('%scopper_grate' % c)}
out = ['# generated by tools/bullet_masks.py: 1 = the pixel stops a bullet (16 rows from the top, 16 pixels each)']
previews = []
for b in sorted(blocks):
    for axis, data in sorted(blocks[b].items()):
        h, bits = mask(data)
        out.append('%s.%s = %s' % (b.replace(':', '\\:'), axis, h))
        previews.append(bits)
open('res/ntmgunfeel-bullet-masks.properties', 'w').write('\n'.join(out) + '\n')
if len(sys.argv) > 3:
    S = 8; W = len(previews) * 17 * S; H = 16 * S
    img = [[(230, 230, 230)] * W for _ in range(H)]
    for k, bits in enumerate(previews):
        for y in range(H):
            for x in range(16 * S):
                if bits[(y // S) * 16 + x // S]: img[y][k * 17 * S + x] = (30, 30, 30)
    raw = b''.join(b'\x00' + bytes(v for p in row for v in p) for row in img)
    ch = lambda t, d: struct.pack('>I', len(d)) + t + d + struct.pack('>I', zlib.crc32(t + d) & 0xffffffff)
    open(sys.argv[3], 'wb').write(b'\x89PNG\r\n\x1a\n' + ch(b'IHDR', struct.pack('>IIBBBBB', W, H, 8, 2, 0, 0, 0)) + ch(b'IDAT', zlib.compress(raw, 9)) + ch(b'IEND', b''))
